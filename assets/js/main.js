// Posts list/grid view toggle
document.addEventListener('DOMContentLoaded', function () {
	var listBtn = document.getElementById('view-list');
	var gridBtn = document.getElementById('view-grid');
	var postList = document.getElementById('post-list');
	var POST_LIST_TOGGLE_KEY = 'mirasol_posts_view';

	if (!postList || (!listBtn && !gridBtn)) return;

	function setView(view) {
		if (view === 'list') {
			postList.classList.remove('row-cols-2');
			postList.classList.add('row-cols-1');
			postList.classList.add('list-view');
			postList.classList.remove('grid-view');
			if (listBtn) listBtn.classList.add('active');
			if (gridBtn) gridBtn.classList.remove('active');
			if (listBtn) listBtn.setAttribute('aria-pressed', 'true');
			if (gridBtn) gridBtn.setAttribute('aria-pressed', 'false');
		} else {
			postList.classList.remove('row-cols-1');
			postList.classList.add('row-cols-2');
			postList.classList.add('grid-view');
			postList.classList.remove('list-view');
			if (gridBtn) gridBtn.classList.add('active');
			if (listBtn) listBtn.classList.remove('active');
			if (gridBtn) gridBtn.setAttribute('aria-pressed', 'true');
			if (listBtn) listBtn.setAttribute('aria-pressed', 'false');
			}
		try { localStorage.setItem(POST_LIST_TOGGLE_KEY, view); } catch (e) {}
	}

	if (listBtn) listBtn.addEventListener('click', function () { setView('list'); });
	if (gridBtn) gridBtn.addEventListener('click', function () { setView('grid'); });

	var saved = null;
	try { saved = localStorage.getItem(POST_LIST_TOGGLE_KEY); } catch (e) {}
	if (saved === 'list' || saved === 'grid') setView(saved); else setView('grid');
});
